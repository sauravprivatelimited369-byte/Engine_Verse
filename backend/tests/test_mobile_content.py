"""The offline lesson library bundled in the Android and Apple apps.

Both apps ship ``content.json`` (full notes at four depths, formulas and the
practice bank) generated by ``scripts/export_mobile_content.py``. These tests
keep the two copies identical, keep the structure the apps decode well-formed,
and keep the exporter honest about what it carries.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
ANDROID = ROOT / "android" / "app" / "src" / "main" / "assets" / "content.json"
APPLE = ROOT / "apple" / "Resources" / "content.json"
LEVELS = ["beginner", "standard", "advanced", "industry"]
RUN_FLAGS = set("bicml")

BLOCK_KINDS = {"p", "h", "ul", "ol", "quote", "code", "math", "table", "hr"}


@pytest.fixture(scope="module")
def content() -> dict:
    return json.loads(ANDROID.read_text(encoding="utf-8"))


def _blocks(document) -> list:
    """Every block list in the document, for structural checks."""
    found = []
    for levels in document["notes"].values():
        for sections in levels.values():
            for section in sections:
                found.extend(section["blocks"])
    for question in document["practice"]:
        found.extend(question["stem"])
        found.extend(question["context"])
        found.extend(question["explanation"])
        for option in question["options"]:
            found.extend(option["body"])
            found.extend(option["why"])
    return found


class TestBundledLibrary:
    def test_both_apps_bundle_the_same_file(self):
        assert ANDROID.read_bytes() == APPLE.read_bytes()

    def test_format_and_levels(self, content):
        assert content["format"] == "engineverse-mobile-content"
        assert content["version"] == 1
        assert content["levels"] == LEVELS

    def test_every_topic_has_all_four_depths(self, content):
        assert len(content["notes"]) >= 400
        for slug, levels in content["notes"].items():
            assert sorted(levels) == sorted(LEVELS), slug
            for sections in levels.values():
                assert sections, slug
                for section in sections:
                    assert section["title"] and section["blocks"], slug

    def test_topics_match_the_catalogue(self, content):
        catalog = json.loads((ROOT / "android" / "app" / "src" / "main" / "assets" / "catalog.json")
                             .read_text(encoding="utf-8"))
        bundled = {t["slug"] for s in catalog["subjects"] for t in s["topics"]}
        assert set(content["notes"]) == bundled

    def test_practice_bank_is_answerable(self, content):
        assert len(content["practice"]) >= 500
        seen = set()
        for question in content["practice"]:
            assert question["slug"] not in seen, question["slug"]
            seen.add(question["slug"])
            assert question["stem"]
            assert len(question["options"]) >= 2
            correct = [o for o in question["options"] if o["correct"]]
            assert len(correct) == 1, question["slug"]
            for option in question["options"]:
                assert option["label"]
                assert option["body"]

    def test_blocks_decode_to_the_documented_shapes(self, content):
        for block in _blocks(content):
            kind = block[0]
            assert kind in BLOCK_KINDS, kind
            if kind == "p":
                assert isinstance(block[1], list)
            elif kind == "h":
                assert isinstance(block[1], int) and isinstance(block[2], list)
            elif kind in ("ul", "ol"):
                assert all(isinstance(item, list) for item in block[1])
            elif kind == "code":
                assert isinstance(block[1], str) and isinstance(block[2], str)
            elif kind == "math":
                assert block[1] and block[2]
            elif kind == "table":
                assert isinstance(block[1], list) and isinstance(block[2], list)
            elif kind == "hr":
                assert len(block) == 1

    def test_runs_are_flagged_and_non_empty(self, content):
        def check(runs):
            for run in runs:
                assert isinstance(run, list) and len(run) == 2, run
                text, flags = run
                assert text, "an empty run would render as a blank gap"
                assert set(flags) <= RUN_FLAGS, flags

        for block in _blocks(content):
            if block[0] in ("p", "quote"):
                check(block[1])
            elif block[0] == "h":
                check(block[2])
            elif block[0] in ("ul", "ol"):
                for item in block[1]:
                    check(item)
            elif block[0] == "table":
                for cell in block[1]:
                    check(cell)
                for row in block[2]:
                    for cell in row:
                        check(cell)

    def test_no_markdown_markers_leak_into_rendered_text(self, content):
        # The apps do not parse Markdown, so nothing may arrive with syntax in it.
        leaks = []
        for block in _blocks(content):
            runs = []
            if block[0] in ("p", "quote"):
                runs = block[1]
            elif block[0] == "h":
                runs = block[2]
            elif block[0] in ("ul", "ol"):
                runs = [run for item in block[1] for run in item]
            elif block[0] == "table":
                runs = [run for cell in block[1] for run in cell]
                runs += [run for row in block[2] for cell in row for run in cell]
            for text, _flags in runs:
                if any(marker in text for marker in ("**", "$$", "```")) and "==" not in text:
                    leaks.append(text[:60])
        assert not leaks, leaks[:5]

    def test_formulas_are_displayable(self, content):
        total = sum(len(rows) for rows in content["formulas"].values())
        assert total >= 300
        for slug, rows in content["formulas"].items():
            for row in rows:
                assert row["name"] and row["latex"], slug
