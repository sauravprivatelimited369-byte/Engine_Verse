import Foundation

/// A piece of inline text in a note, already resolved from Markdown by
/// `scripts/export_mobile_content.py`. The apps never parse Markdown at
/// runtime; they only lay these runs out, so a note reads the same on every
/// device and needs no web page.
public struct Run: Equatable, Sendable {
    public let text: String
    public let bold: Bool
    public let italic: Bool
    public let code: Bool
    public let math: Bool

    public init(text: String, bold: Bool = false, italic: Bool = false, code: Bool = false, math: Bool = false) {
        self.text = text
        self.bold = bold
        self.italic = italic
        self.code = code
        self.math = math
    }
}

/// A block of a note section or question. Mirrors the exporter's block list.
public enum Block: Equatable, Sendable {
    case paragraph([Run])
    case heading(level: Int, runs: [Run])
    case bullets([[Run]])
    case numbers([[Run]])
    case quote([Run])
    case code(text: String, language: String)
    /// `plain` is a readable form of `latex` for display.
    case math(latex: String, plain: String)
    case table(head: [[Run]], rows: [[[Run]]])
    case rule
}

/// One of the thirteen note sections (definition, formula, derivation, ...).
public struct LessonSection: Equatable, Sendable {
    public let kind: String
    public let title: String
    public let callout: String
    public let blocks: [Block]
}

public struct Formula: Equatable, Sendable {
    public let name: String
    public let latex: String
    public let meaning: String
    public let application: String
}

public struct PracticeOption: Equatable, Sendable {
    public let label: String
    public let body: [Block]
    public let correct: Bool
    public let why: [Block]
}

public struct PracticeQuestion: Equatable, Sendable, Identifiable {
    public var id: String { slug }
    public let slug: String
    public let subject: String
    public let topic: String
    public let difficulty: String
    public let stem: [Block]
    public let context: [Block]
    public let options: [PracticeOption]
    public let explanation: [Block]

    /// The first paragraph of the stem, for lists and headers.
    public var headline: String {
        for block in stem {
            if case let .paragraph(runs) = block {
                let text = runs.map(\.text).joined(separator: " ")
                if !text.isEmpty {
                    return String(text.prefix(160))
                }
            }
        }
        return slug
    }
}

/// The full offline lesson library: every topic at four note depths, its
/// formulas and the practice bank. Read from `content.json` in the app bundle,
/// generated by `scripts/export_mobile_content.py`.
public final class LessonLibrary: Sendable {
    public static let empty = LessonLibrary(levels: [], notes: [:], formulas: [:], questions: [])

    public let levels: [String]
    private let notes: [String: [String: [LessonSection]]]
    public let formulas: [String: [Formula]]
    public let questions: [PracticeQuestion]
    private let questionIndex: [String: PracticeQuestion]

    public var isEmpty: Bool { notes.isEmpty && questions.isEmpty }
    public var topicCount: Int { notes.count }

    public init(
        levels: [String],
        notes: [String: [String: [LessonSection]]],
        formulas: [String: [Formula]],
        questions: [PracticeQuestion]
    ) {
        self.levels = levels.isEmpty ? ["beginner", "standard", "advanced", "industry"] : levels
        self.notes = notes
        self.formulas = formulas
        self.questions = questions
        var index: [String: PracticeQuestion] = [:]
        for question in questions { index[question.slug] = question }
        self.questionIndex = index
    }

    /// Note depths that exist for this topic, in reading order.
    public func availableLevels(_ topic: String) -> [String] {
        levels.filter { notes[topic]?[$0] != nil }
    }

    public func sections(topic: String, level: String) -> [LessonSection] {
        notes[topic]?[level] ?? []
    }

    public func hasNotes(_ topic: String) -> Bool {
        !(notes[topic]?.isEmpty ?? true)
    }

    public func question(_ slug: String) -> PracticeQuestion? {
        questionIndex[slug]
    }

    public func questions(forTopic topic: String) -> [PracticeQuestion] {
        questions.filter { $0.topic == topic }
    }

    public func questions(forSubject subject: String) -> [PracticeQuestion] {
        questions.filter { $0.subject == subject }
    }

    /// Display names for the four note depths.
    public static func levelName(_ level: String) -> String {
        switch level {
        case "beginner": return "Beginner"
        case "standard": return "Standard"
        case "advanced": return "Advanced"
        case "industry": return "Industry"
        default: return level.prefix(1).uppercased() + level.dropFirst()
        }
    }

    // MARK: - Decoding

    public static func decode(from data: Data) throws -> LessonLibrary {
        guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any],
              root["format"] as? String == "engineverse-mobile-content",
              (root["version"] as? Int) == 1
        else {
            throw CocoaError(.coderReadCorrupt)
        }

        let levels = (root["levels"] as? [Any])?.compactMap { $0 as? String } ?? []
        var notes: [String: [String: [LessonSection]]] = [:]
        if let topicDocument = root["notes"] as? [String: Any] {
            for (slug, value) in topicDocument {
                guard let byLevel = value as? [String: Any] else { continue }
                var parsed: [String: [LessonSection]] = [:]
                for (level, rawSections) in byLevel {
                    guard let rawSections = rawSections as? [Any] else { continue }
                    let sections = rawSections.compactMap { section(from: $0) }
                    if !sections.isEmpty { parsed[level] = sections }
                }
                if !parsed.isEmpty { notes[slug] = parsed }
            }
        }

        var formulas: [String: [Formula]] = [:]
        if let formulaDocument = root["formulas"] as? [String: Any] {
            for (slug, value) in formulaDocument {
                guard let rows = value as? [Any] else { continue }
                let parsed = rows.compactMap { row -> Formula? in
                    guard let row = row as? [String: Any] else { return nil }
                    let latex = row["latex"] as? String ?? ""
                    return Formula(
                        name: row["name"] as? String ?? "",
                        latex: latex,
                        meaning: row["meaning"] as? String ?? "",
                        application: row["application"] as? String ?? ""
                    )
                }
                if !parsed.isEmpty { formulas[slug] = parsed }
            }
        }

        var questions: [PracticeQuestion] = []
        if let rawQuestions = root["practice"] as? [Any] {
            for raw in rawQuestions {
                guard let question = raw as? [String: Any],
                      let slug = question["slug"] as? String, !slug.isEmpty
                else { continue }
                let options = (question["options"] as? [Any])?.compactMap { value -> PracticeOption? in
                    guard let option = value as? [String: Any] else { return nil }
                    return PracticeOption(
                        label: option["label"] as? String ?? "",
                        body: blocks(option["body"]),
                        correct: option["correct"] as? Bool ?? false,
                        why: blocks(option["why"])
                    )
                } ?? []
                guard options.count >= 2, options.contains(where: \.correct) else { continue }
                questions.append(PracticeQuestion(
                    slug: slug,
                    subject: question["subject"] as? String ?? "",
                    topic: question["topic"] as? String ?? "",
                    difficulty: question["difficulty"] as? String ?? "medium",
                    stem: blocks(question["stem"]),
                    context: blocks(question["context"]),
                    options: options,
                    explanation: blocks(question["explanation"])
                ))
            }
        }

        return LessonLibrary(levels: levels, notes: notes, formulas: formulas, questions: questions)
    }

    public static func loadBundled() -> LessonLibrary {
        if let url = Bundle.main.url(forResource: "content", withExtension: "json"),
           let data = try? Data(contentsOf: url),
           let library = try? decode(from: data) {
            return library
        }
        // Fallback when launched directly with `swift run` from apple/.
        let cwdURL = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
            .appendingPathComponent("Resources/content.json")
        if let data = try? Data(contentsOf: cwdURL),
           let library = try? decode(from: data) {
            return library
        }
        return .empty
    }

    private static func section(from value: Any) -> LessonSection? {
        guard let object = value as? [String: Any] else { return nil }
        let title = object["title"] as? String ?? ""
        let parsed = blocks(object["blocks"])
        if title.isEmpty && parsed.isEmpty { return nil }
        return LessonSection(
            kind: object["kind"] as? String ?? "",
            title: title.isEmpty ? "Notes" : title,
            callout: object["callout"] as? String ?? "",
            blocks: parsed
        )
    }

    private static func blocks(_ value: Any?) -> [Block] {
        guard let raw = value as? [Any] else { return [] }
        return raw.compactMap { block(from: $0) }
    }

    private static func block(from value: Any) -> Block? {
        guard let raw = value as? [Any], let kind = raw.first as? String else { return nil }
        switch kind {
        case "p":
            return .paragraph(runs(raw.count > 1 ? raw[1] : nil))
        case "h":
            let level = (raw.count > 1 ? raw[1] as? Int : nil) ?? 2
            return .heading(level: level, runs: runs(raw.count > 2 ? raw[2] : nil))
        case "ul":
            return .bullets(items(raw.count > 1 ? raw[1] : nil))
        case "ol":
            return .numbers(items(raw.count > 1 ? raw[1] : nil))
        case "quote":
            return .quote(runs(raw.count > 1 ? raw[1] : nil))
        case "code":
            return .code(
                text: raw.count > 1 ? (raw[1] as? String ?? "") : "",
                language: raw.count > 2 ? (raw[2] as? String ?? "") : ""
            )
        case "math":
            let latex = raw.count > 1 ? (raw[1] as? String ?? "") : ""
            let plain = raw.count > 2 ? (raw[2] as? String ?? "") : ""
            return .math(latex: latex, plain: plain.isEmpty ? latex : plain)
        case "table":
            let head = rows(raw.count > 1 ? raw[1] : nil)
            let body = (raw.count > 2 ? raw[2] as? [Any] : nil)?.map { rows($0) } ?? []
            return .table(head: head, rows: body)
        case "hr":
            return .rule
        default:
            return nil
        }
    }

    private static func items(_ value: Any?) -> [[Run]] {
        guard let raw = value as? [Any] else { return [] }
        return raw.map { runs($0) }.filter { !$0.isEmpty }
    }

    private static func rows(_ value: Any?) -> [[Run]] {
        guard let raw = value as? [Any] else { return [] }
        return raw.map { runs($0) }
    }

    private static func runs(_ value: Any?) -> [Run] {
        guard let raw = value as? [Any] else { return [] }
        return raw.compactMap { item in
            guard let pair = item as? [Any], let text = pair.first as? String, !text.isEmpty else { return nil }
            let flags = pair.count > 1 ? (pair[1] as? String ?? "") : ""
            return Run(
                text: text,
                bold: flags.contains("b"),
                italic: flags.contains("i"),
                code: flags.contains("c"),
                math: flags.contains("m")
            )
        }
    }
}
