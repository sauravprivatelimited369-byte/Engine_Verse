package io.github.sauravprivatelimited369byte.engineverse.core

/**
 * A piece of inline text inside a note or question, already resolved from
 * Markdown by scripts/export_mobile_content.py. The apps never parse Markdown
 * at runtime: they only lay these spans out, so both platforms render the same
 * words identically.
 */
data class Span(
    val text: String,
    val bold: Boolean = false,
    val italic: Boolean = false,
    val code: Boolean = false,
    val math: Boolean = false,
)

/** A block of a note section or question. Mirrors the exporter's block list. */
sealed interface Block {
    data class Paragraph(val spans: List<Span>) : Block
    data class Heading(val level: Int, val spans: List<Span>) : Block
    data class Bullets(val items: List<List<Span>>) : Block
    data class Numbers(val items: List<List<Span>>) : Block
    data class Quote(val spans: List<Span>) : Block
    data class Code(val text: String, val language: String) : Block
    /** [plain] is a readable form of [latex] for display; [latex] is kept for copying. */
    data class Math(val latex: String, val plain: String) : Block
    data class Table(val head: List<List<Span>>, val rows: List<List<List<Span>>>) : Block
    data object Rule : Block
}

/** One of the thirteen note sections (definition, formula, derivation, ...). */
data class LessonSection(
    val kind: String,
    val title: String,
    val callout: String,
    val blocks: List<Block>,
)

data class Formula(
    val name: String,
    val latex: String,
    val plain: String,
    val meaning: String,
    val application: String,
)

data class PracticeOption(
    val label: String,
    val body: List<Block>,
    val correct: Boolean,
    val why: List<Block>,
)

data class PracticeQuestion(
    val slug: String,
    val subject: String,
    val topic: String,
    val difficulty: String,
    val stem: List<Block>,
    val context: List<Block>,
    val options: List<PracticeOption>,
    val explanation: List<Block>,
) {
    /** The first paragraph of the stem, for lists and headers. */
    val headline: String
        get() = stem.filterIsInstance<Block.Paragraph>().firstOrNull()
            ?.spans?.joinToString(" ") { it.text }
            ?.take(160)
            ?: slug
}

/**
 * The full offline lesson library: every topic at four note depths, its
 * formulas and the practice bank. Read from assets/content.json, generated by
 * scripts/export_mobile_content.py.
 */
class LessonLibrary(
    val levels: List<String>,
    private val notes: Map<String, Map<String, List<LessonSection>>>,
    val formulas: Map<String, List<Formula>>,
    val questions: List<PracticeQuestion>,
) {
    private val questionIndex: Map<String, PracticeQuestion> = questions.associateBy { it.slug }

    val isEmpty: Boolean get() = notes.isEmpty() && questions.isEmpty()
    val topicCount: Int get() = notes.size

    /** Note depths that actually exist for this topic, in reading order. */
    fun availableLevels(topic: String): List<String> =
        levels.filter { notes[topic]?.containsKey(it) == true }

    fun sections(topic: String, level: String): List<LessonSection> =
        notes[topic]?.get(level).orEmpty()

    fun hasNotes(topic: String): Boolean = notes[topic]?.isNotEmpty() == true

    fun question(slug: String): PracticeQuestion? = questionIndex[slug]

    fun questionsForTopic(topic: String): List<PracticeQuestion> =
        questions.filter { it.topic == topic }

    fun questionsForSubject(subject: String): List<PracticeQuestion> =
        questions.filter { it.subject == subject }

    companion object {
        val EMPTY = LessonLibrary(emptyList(), emptyMap(), emptyMap(), emptyList())

        /** Display names for the four note depths. */
        fun levelName(level: String): String = when (level) {
            "beginner" -> "Beginner"
            "standard" -> "Standard"
            "advanced" -> "Advanced"
            "industry" -> "Industry"
            else -> level.replaceFirstChar { it.uppercase() }
        }
    }
}
